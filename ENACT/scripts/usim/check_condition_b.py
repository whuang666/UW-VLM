"""Independent audit of the condition-B (full frame + 2x zoom) assets.

Condition B is generated by the frozen ``build_crops.py``.  That script records only
aggregate rule counts in ``build_manifest.json``, so the per-frame framing decision is
not auditable from its own output.  This checker therefore re-derives every framing
decision from the source frames and re-composites each stored image from scratch, then
compares the result byte-for-byte against what is on disk.

Checks performed (any failure makes the script exit non-zero):

1. **Set equality** -- same question count, same ID order, and identical
   ``task_name`` / ``type`` / ``key_frame_ids`` / ``question`` / ``answer`` / ``options``
   as the source QA, with ``source_images`` pointing back at the condition-A images.
   Condition B must differ from A in images only.
2. **Geometry** -- every composite exists and is 320x2 x 240.
3. **Left panel identity** -- ``composite[:, :320]`` is byte-identical to the
   condition-A image, so the only experimental change is the added zoom panel.
4. **Rule recomputation** -- rule counts recomputed from the source frames must match
   ``build_manifest.json``.
5. **Re-composition** -- rebuilding each composite with the frozen ``compose()`` must
   reproduce the stored PNG exactly.
6. **Target visibility** -- for episodes with a detectable target colour, the fraction
   of the target blob area that falls inside the zoom window is measured, so frames
   whose zoom panel clips or misses the target are reported rather than assumed fine.

Output is a JSON evidence file (no timestamps) so it can be frozen and re-verified.

Usage:
    python scripts/usim/check_condition_b.py \
        --data-root data/usim_enact/usim-enact-v0.2 \
        --source-qa data/usim_enact/usim-enact-v0.2/QA/train/enact_ordering_curated.jsonl \
        --condition-qa data/usim_enact/usim-enact-v0.2/QA/conditions/B_zoom/enact_ordering.jsonl \
        --out data/usim_enact/_protocol/condition_b_check_usim-enact-v0.2.json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.usim.annotate_helper import colour_blobs  # noqa: E402
from scripts.usim.build_crops import (  # noqa: E402
    anchored_window,
    compose,
    episode_object_colour,
)

DEFAULT_DATA_ROOT = ROOT / "data" / "usim_enact" / "usim-enact-v0.2"
LABEL_BAND = 56  # rows reserved at the top of every presented frame for the state label


def load_jsonl(path: Path) -> List[Dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def resolve_path(data_root: Path, relative: str) -> Path:
    return data_root / str(relative).replace("\\", "/")


def load_frames(data_root: Path, task_name: str) -> Dict[str, np.ndarray]:
    sensor_dir = data_root / "replayed_activities" / task_name / "external_sensor1"
    return {path.stem: cv2.imread(str(path)) for path in sorted(sensor_dir.glob("*.png"))}


def match_source_frame(frames: Dict[str, np.ndarray], presented: np.ndarray) -> Tuple[str, float]:
    """Map a presented image back to the clean source frame it was rendered from."""
    body = presented[LABEL_BAND:, :, :].astype(np.int16)
    best_name, best_score = None, None
    for name, raw in frames.items():
        score = float(np.mean(np.abs(raw[LABEL_BAND:, :, :].astype(np.int16) - body)))
        if best_score is None or score < best_score:
            best_name, best_score = name, score
    if best_name is None:
        raise RuntimeError("no source frame candidate")
    return best_name, best_score


def blob_coverage(blob: Dict[str, float], window: Tuple[int, int, int, int]) -> Optional[float]:
    """Fraction of the blob's bounding-box area that lies inside the zoom window."""
    if not blob or blob.get("area", 0) <= 0 or not blob.get("w") or not blob.get("h"):
        return None
    x0, y0, x1, y1 = window
    bx0, by0 = blob["x"], blob["y"]
    bx1, by1 = bx0 + blob["w"], by0 + blob["h"]
    ix = max(0, min(bx1, x1) - max(bx0, x0))
    iy = max(0, min(by1, y1) - max(by0, y0))
    return (ix * iy) / float(blob["w"] * blob["h"])


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data-root", default=str(DEFAULT_DATA_ROOT))
    parser.add_argument("--source-qa", default="")
    parser.add_argument("--condition-qa", default="")
    parser.add_argument("--out", default="")
    args = parser.parse_args(argv)

    data_root = Path(args.data_root).resolve()
    source_qa = Path(args.source_qa).resolve() if args.source_qa else data_root / "QA" / "train" / "enact_ordering_curated.jsonl"
    condition_root = data_root / "QA" / "conditions" / "B_zoom"
    condition_qa = Path(args.condition_qa).resolve() if args.condition_qa else condition_root / "enact_ordering.jsonl"
    out_path = (Path(args.out).resolve() if args.out
                else ROOT / "data" / "usim_enact" / "_protocol" / "condition_b_check_usim-enact-v0.2.json")

    source = load_jsonl(source_qa)
    condition = load_jsonl(condition_qa)
    manifest = json.loads((condition_root / "build_manifest.json").read_text(encoding="utf-8"))

    failures: List[str] = []
    checks: Dict[str, Any] = {}

    # ---------------------------------------------------------------- 1. set equality
    if len(source) != len(condition):
        failures.append(f"question count {len(condition)} != source {len(source)}")
    source_ids = [record["id"] for record in source]
    condition_ids = [record["id"] for record in condition]
    if source_ids != condition_ids:
        failures.append("question ID order differs from source QA")
    field_mismatches: List[Dict[str, str]] = []
    for src, cond in zip(source, condition):
        for field in ("task_name", "type", "key_frame_ids", "question", "answer", "options"):
            if src.get(field) != cond.get(field):
                field_mismatches.append({"id": src["id"], "field": field})
        if cond.get("source_images") != src["images"]:
            field_mismatches.append({"id": src["id"], "field": "source_images"})
    if field_mismatches:
        failures.append(f"{len(field_mismatches)} field mismatches against source QA")
    checks["set_equality"] = {
        "questions_source": len(source),
        "questions_condition": len(condition),
        "id_order_identical": source_ids == condition_ids,
        "field_mismatches": field_mismatches[:20],
        "field_mismatch_count": len(field_mismatches),
    }

    # ------------------------------------------- 2..5. per-image geometry / identity / rules
    frames_cache: Dict[str, Dict[str, np.ndarray]] = {}
    colours: Dict[str, Optional[str]] = {}
    rule_counts: Dict[str, int] = {}
    window_sides: List[int] = []
    shapes: Dict[str, int] = {}
    missing: List[str] = []
    left_panel_diff: List[str] = []
    recompose_diff: List[str] = []
    ambiguous_match: List[Dict[str, Any]] = []
    coverage_rows: List[Dict[str, Any]] = []

    for src, cond in zip(source, condition):
        task = cond["task_name"]
        if task not in frames_cache:
            frames_cache[task] = load_frames(data_root, task)
            colours[task] = episode_object_colour(data_root, task)
        frames = frames_cache[task]

        for position, relative in enumerate(cond["images"]):
            path = resolve_path(data_root, relative)
            if not path.exists():
                missing.append(relative)
                continue
            composite = cv2.imread(str(path))
            key = f"{composite.shape[0]}x{composite.shape[1]}x{composite.shape[2]}"
            shapes[key] = shapes.get(key, 0) + 1

            # 3. left panel must be the untouched condition-A image
            source_image = cv2.imread(str(resolve_path(data_root, src["images"][position])))
            if source_image is None or composite.shape != (source_image.shape[0], source_image.shape[1] * 2, 3):
                left_panel_diff.append(relative)
                continue
            if not np.array_equal(composite[:, : source_image.shape[1]], source_image):
                left_panel_diff.append(relative)

            # 4. recompute framing from the clean source frame
            frame_name, score = match_source_frame(frames, source_image)
            frame = frames[frame_name]
            scores = sorted(
                float(np.mean(np.abs(raw[LABEL_BAND:, :, :].astype(np.int16) - source_image[LABEL_BAND:, :, :].astype(np.int16))))
                for raw in frames.values()
            )
            if len(scores) > 1 and (scores[1] - scores[0]) < 1.0:
                ambiguous_match.append({"image": relative, "score": round(score, 4)})
            window, rule = anchored_window(frame, colours[task])
            rule_counts[rule] = rule_counts.get(rule, 0) + 1
            window_sides.append(int(window[2] - window[0]))

            # 5. rebuild the composite with the frozen renderer and compare exactly
            label = "Current State" if position == 0 else f"Next State {position}"
            rebuilt = compose(frame, window, label)
            if rebuilt.shape != composite.shape or not np.array_equal(rebuilt, composite):
                recompose_diff.append(relative)

            # 6. target visibility inside the zoom window -- red only.
            # The largest blue blob in these frames is the water body itself, so a blue
            # "coverage" number measures the water, not the target; green marks the
            # landmark box, not the manipulated object.  Both are excluded here.
            colour = colours[task]
            if colour == "red":
                blob = colour_blobs(frame)[colour]
                coverage = blob_coverage(blob, window)
                if coverage is not None and blob["area"] >= 12:
                    coverage_rows.append(
                        {
                            "image": relative,
                            "episode": task,
                            "frame": frame_name,
                            "colour": colour,
                            "rule": rule,
                            "coverage": round(coverage, 4),
                            "centroid_inside": bool(
                                window[0] <= blob["cx"] <= window[2] and window[1] <= blob["cy"] <= window[3]
                            ),
                        }
                    )

    if missing:
        failures.append(f"{len(missing)} missing composites")
    if left_panel_diff:
        failures.append(f"{len(left_panel_diff)} composites whose left panel differs from condition A")
    if recompose_diff:
        failures.append(f"{len(recompose_diff)} composites not reproducible by frozen compose()")
    if rule_counts != manifest.get("rule_counts"):
        failures.append(f"rule counts {rule_counts} != manifest {manifest.get('rule_counts')}")

    checks["geometry"] = {"shapes": shapes, "missing": missing[:20], "missing_count": len(missing)}
    checks["left_panel_identity"] = {"mismatch_count": len(left_panel_diff), "examples": left_panel_diff[:10]}
    checks["framing"] = {
        "rule_counts_recomputed": rule_counts,
        "rule_counts_manifest": manifest.get("rule_counts"),
        "window_side_min": min(window_sides) if window_sides else None,
        "window_side_max": max(window_sides) if window_sides else None,
        "implied_zoom_factor_min": round(320.0 / max(window_sides), 4) if window_sides else None,
        "implied_zoom_factor_max": round(320.0 / min(window_sides), 4) if window_sides else None,
        "ambiguous_source_match": ambiguous_match[:10],
    }
    checks["recomposition"] = {"mismatch_count": len(recompose_diff), "examples": recompose_diff[:10]}

    # 6. summarise coverage
    if coverage_rows:
        coverages = sorted(row["coverage"] for row in coverage_rows)
        clipped = [row for row in coverage_rows if row["coverage"] < 1.0]
        outside = [row for row in coverage_rows if not row["centroid_inside"]]
        checks["target_visibility"] = {
            "measured_colour": "red",
            "frames_measured": len(coverage_rows),
            "coverage_min": round(coverages[0], 4),
            "coverage_median": round(coverages[len(coverages) // 2], 4),
            "frames_fully_inside": sum(1 for value in coverages if value >= 1.0),
            "frames_partially_clipped": len(clipped),
            "frames_centroid_outside": len(outside),
            "clipped_examples": clipped[:10],
            "excluded_colours": {
                "blue": "the largest blue blob is the water body, so coverage would measure the "
                        "water rather than the target; blue episodes use the R2 fixed window by policy",
                "green": "green marks the landmark box, not the manipulated target",
            },
            "note": "coverage is an audit signal for the red target, not a crop rule",
        }
    else:
        checks["target_visibility"] = {"frames_measured": 0}

    evidence = {
        "schema": "usim-condition-b-check/1",
        "dataset": data_root.name,
        "condition": "B_zoom",
        "source_qa": str(source_qa.relative_to(ROOT)).replace("\\", "/"),
        "source_qa_sha256": sha256_file(source_qa),
        "condition_qa": str(condition_qa.relative_to(ROOT)).replace("\\", "/"),
        "condition_qa_sha256": sha256_file(condition_qa),
        "images": sum(len(record["images"]) for record in condition),
        "status": "pass" if not failures else "fail",
        "failures": failures,
        "checks": checks,
    }

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(evidence, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(json.dumps({"status": evidence["status"], "failures": failures,
                      "rule_counts": rule_counts, "recompose_diff": len(recompose_diff),
                      "left_panel_diff": len(left_panel_diff)}, ensure_ascii=False))
    print(f"evidence: {out_path}")
    return 0 if not failures else 1


if __name__ == "__main__":
    raise SystemExit(main())
